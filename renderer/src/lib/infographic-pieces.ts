// Banco de peças do infográfico (viewBox 100x100). Cada peça é um objeto reconhecível, desenhado em
// formas simples com os tons abaixo; o estilo "papel facetado" (facetas, contorno branco de adesivo e
// sombra) é aplicado por `InfographicPiece` (ver `docs/infografico.md`). O catálogo que a IA vê fica em
// `shared/infographic-pieces.ts`; um teste garante que as chaves, nomes e tags são os mesmos.
//
// Tons: `b` destaque, `B` destaque escuro, `s` destaque suave, `n` cinza claro, `N` cinza médio,
// `d` cinza escuro e `w` cartão (brilhos e detalhes claros). `box` é a caixa que a peça ocupa.

export type Tone = 'b' | 'B' | 's' | 'n' | 'N' | 'd' | 'w';

export type Shape =
  | ['r', number, number, number, number, Tone, number]
  | ['c', number, number, number, Tone]
  | ['e', number, number, number, number, Tone]
  | ['g', number[], Tone]
  | ['a', string, Tone]
  | ['l', number, number, number, number, Tone, number]
  | ['k', string, Tone, number]
  | ['o', number, number, number, Tone, number]
  | ['q', number, number, number, number, Tone, number]
  | ['T', number, number, number, Shape[]];

export interface Piece {
  key: string;
  theme: string;
  name: string;
  tags: string;
  shapes: Shape[];
  /** Caixa da peça no desenho (`[x, y, largura, altura]`), para centralizar e ajustar no quadro. */
  box: [number, number, number, number];
}

